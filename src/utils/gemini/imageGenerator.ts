import type { SupabaseClient } from "@supabase/supabase-js";

export interface GeminiGeneratedImage {
  base64Data: string;
  mimeType: string;
  model: string;
}

interface InteractionContentBlock {
  type?: string;
  data?: string;
  mime_type?: string;
  image?: {
    data?: string;
    mime_type?: string;
  };
}

interface InteractionStep {
  type?: string;
  content?: InteractionContentBlock[];
}

interface InteractionResponse {
  output_image?: {
    data?: string;
    mime_type?: string;
  };
  steps?: InteractionStep[];
}

/**
 * Generates an image using the Gemini Interactions API (`gemini-nano-banana-2.1`).
 */
export async function generateImageWithGemini({
  prompt,
  apiKey,
  model = "gemini-nano-banana-2.1",
}: {
  prompt: string;
  apiKey?: string;
  model?: "gemini-nano-banana-2.1" | "gemini-3.1-flash-lite-image" | "gemini-3-pro-image";
}): Promise<GeminiGeneratedImage | null> {
  const resolvedKey = (
    apiKey ||
    process.env.GEMINI_API_KEY ||
    process.env.GOOGLE_API_KEY ||
    ""
  ).trim();

  if (!resolvedKey || resolvedKey === "your-gemini-api-key") {
    return null;
  }

  try {
    const response = await fetch(
      "https://generativelanguage.googleapis.com/v1beta/interactions",
      {
        method: "POST",
        headers: {
          "x-goog-api-key": resolvedKey,
          "Content-Type": "application/json",
          "Api-Revision": "2026-05-20",
        },
        body: JSON.stringify({
          model,
          input: [{ type: "text", text: prompt }],
        }),
      }
    );

    if (!response.ok) {
      return null;
    }

    const payload = (await response.json()) as InteractionResponse;

    // 1. Check convenience property `output_image`
    if (payload.output_image?.data) {
      return {
        base64Data: payload.output_image.data,
        mimeType: payload.output_image.mime_type || "image/png",
        model,
      };
    }

    // 2. Fallback: walk `steps` for `model_output` image content blocks
    for (const step of payload.steps || []) {
      if (step.type === "model_output" && Array.isArray(step.content)) {
        for (const block of step.content) {
          if (block.type === "image" && block.data) {
            return {
              base64Data: block.data,
              mimeType: block.mime_type || "image/png",
              model,
            };
          }
          if (block.image?.data) {
            return {
              base64Data: block.image.data,
              mimeType: block.image.mime_type || "image/png",
              model,
            };
          }
        }
      }
    }

    return null;
  } catch {
    return null;
  }
}

/**
 * Uploads a base64-encoded image generated by Gemini into the Supabase Storage
 * bucket (`ai-plate-images`) and returns its public URL.
 */
export async function uploadGeneratedImageToSupabase({
  supabase,
  bucket = "ai-plate-images",
  storagePath,
  base64Data,
  mimeType = "image/png",
}: {
  supabase: SupabaseClient;
  bucket?: string;
  storagePath: string;
  base64Data: string;
  mimeType?: string;
}): Promise<string | null> {
  const buffer = Buffer.from(base64Data, "base64");
  const { error: uploadError } = await supabase.storage
    .from(bucket)
    .upload(storagePath, buffer, {
      contentType: mimeType,
      upsert: true,
    });

  if (uploadError) {
    return null;
  }

  const { data: urlData } = supabase.storage
    .from(bucket)
    .getPublicUrl(storagePath);

  return urlData?.publicUrl ?? null;
}

